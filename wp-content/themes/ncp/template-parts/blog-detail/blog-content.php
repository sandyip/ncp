  <h3>Steps for Optimizing a Blog Post</h3>
  <ol>
    <li>Research primary and secondary keywords.</li>
    <li>Write a compelling, keyword-rich title.</li>
    <li>Optimize your meta description.</li>
    <li>Use headings strategically for clarity.</li>
    <li>Add internal and external links.</li>
    <li>Optimize images with alt tags.</li>
    <li>Ensure mobile responsiveness.</li>
    <li>Publish and submit to Google Search Console.</li>
  </ol>

